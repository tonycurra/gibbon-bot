"""Generate procedural olive tree(s) → data/grove.xml.

Phase 1: one tree, primitive-based (capsules + ellipsoids).
Trunk has collision (climbable). Branches and foliage are visual-only.

Examples:
    # mature olive, default position
    python gen_grove.py

    # ancient gnarled tree, big and spread out
    python gen_grove.py --variety ancient --size 1.3 --detachment 0.6

    # young sapling
    python gen_grove.py --variety young --leaves 0.8 --branches 3

Parameters (terms tuned for olives):
    --variety       young | mature | ancient
    --size          scalar multiplier on overall dimensions
    --branches      override branch count (else preset by variety)
    --leaves        0..1 foliage density (cluster radius scale)
    --detachment    0..1 canopy openness (0=tight, 1=spread)
    --pos x y       base position; z is sampled from terrain.png
    --seed          rng seed (changes bend, branch angles, jitter)
"""
import argparse
import re
from pathlib import Path

import numpy as np
from PIL import Image

VARIETIES = {
    "young":   dict(height=1.4, base_r=0.07, top_r=0.04, gnarl=0.08, canopy=0.55, fol_r=0.30, n_branches=3),
    "mature":  dict(height=2.4, base_r=0.18, top_r=0.10, gnarl=0.22, canopy=0.95, fol_r=0.55, n_branches=5),
    "ancient": dict(height=2.0, base_r=0.30, top_r=0.18, gnarl=0.55, canopy=1.10, fol_r=0.75, n_branches=6),
}

p = argparse.ArgumentParser()
p.add_argument("--variety", choices=list(VARIETIES.keys()), default="mature")
p.add_argument("--size", type=float, default=1.0)
p.add_argument("--branches", type=int, default=None)
p.add_argument("--leaves", type=float, default=0.6)
p.add_argument("--detachment", type=float, default=0.3)
p.add_argument("--pos", type=float, nargs=2, default=[2.0, 0.0])
p.add_argument("--seed", type=int, default=42)
args = p.parse_args()

V = VARIETIES[args.variety]
size = max(0.3, args.size)
height = V["height"] * size
base_r = V["base_r"] * size
top_r  = V["top_r"]  * size
gnarl  = V["gnarl"]
canopy = V["canopy"] * size
fol_r  = V["fol_r"]  * size
n_branches = max(2, min(8, args.branches if args.branches is not None else V["n_branches"]))
leaves = max(0.1, min(1.0, args.leaves))
detach = max(0.0, min(1.0, args.detachment))

rng = np.random.default_rng(args.seed)

TERRAIN = Path("data/terrain.xml")
PNG     = Path("data/terrain.png")
GROVE   = Path("data/grove.xml")
HALF    = 5.0

# ---------- terrain height sampling ----------
def terrain_height_at(x: float, y: float) -> float:
    img = np.asarray(Image.open(PNG).convert("L")) / 255.0
    h, w = img.shape
    m = re.search(r'<hfield\b[^>]*\bsize="\S+\s+\S+\s+([\d.]+)', TERRAIN.read_text())
    zmax = float(m.group(1)) if m else 1.0
    u = float(np.clip((x + HALF) / (2 * HALF), 0, 1))
    v = float(np.clip((HALF - y) / (2 * HALF), 0, 1))
    return float(img[int(v * (h - 1)), int(u * (w - 1))]) * zmax

bx, by = args.pos
bz = terrain_height_at(bx, by) - 0.05  # bury base 5cm

# ---------- trunk (4 capsules along a slightly bent curve) ----------
N_TRUNK = 4
trunk_pts = []
for i in range(N_TRUNK + 1):
    t = i / N_TRUNK
    # gnarled bend — two perpendicular sine waves at different frequencies
    dx = gnarl * np.sin(t * 1.7 * np.pi) * 0.35 * rng.uniform(0.7, 1.3)
    dy = gnarl * np.sin(t * 2.3 * np.pi + 0.7) * 0.35 * rng.uniform(0.7, 1.3)
    trunk_pts.append((bx + dx, by + dy, bz + t * height))

trunk_caps = []  # (p0, p1, radius)
for i in range(N_TRUNK):
    t = (i + 0.5) / N_TRUNK
    r = base_r + (top_r - base_r) * t
    trunk_caps.append((trunk_pts[i], trunk_pts[i+1], r))

# ---------- branches (capsules off upper trunk) ----------
branches = []
for b in range(n_branches):
    # branch height: upper 60% of trunk, jittered
    t = rng.uniform(0.4, 0.9)
    seg = min(int(t * N_TRUNK), N_TRUNK - 1)
    p0 = np.array(trunk_pts[seg])
    az = 2 * np.pi * b / n_branches + rng.uniform(-0.4, 0.4)
    el = rng.uniform(np.pi / 7, np.pi / 2.3)            # 25–78° from horizontal
    blen = canopy * rng.uniform(0.7, 1.2)
    direction = np.array([np.cos(az) * np.cos(el), np.sin(az) * np.cos(el), np.sin(el)])
    p1 = p0 + direction * blen
    r0 = top_r * rng.uniform(0.45, 0.7)
    branches.append((tuple(p0), tuple(p1), r0))

# ---------- foliage clusters ----------
foliage = []  # (center, [rx, ry, rz])
crown = np.array(trunk_pts[-1]) + np.array([0, 0, fol_r * 0.4])
foliage.append((crown, [fol_r * 1.0, fol_r * 1.0, fol_r * 0.6]))
for (_, p1, _) in branches:
    p1a = np.array(p1)
    spread = 1.0 - 0.55 * detach
    fr = fol_r * leaves * rng.uniform(0.6, 1.0) * spread
    foliage.append((p1a, [fr * 1.1, fr * 1.1, fr * 0.7]))

# ---------- write grove.xml ----------
def f3(v): return f"{v[0]:.3f} {v[1]:.3f} {v[2]:.3f}"
def f6(a, b): return f"{a[0]:.3f} {a[1]:.3f} {a[2]:.3f} {b[0]:.3f} {b[1]:.3f} {b[2]:.3f}"

BARK   = "0.36 0.27 0.18 1"     # warm brown
LEAVES = "0.42 0.55 0.32 1"     # olive-green

lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- generated by gen_grove.py -->',
    '<mujocoinclude>',
    '  <worldbody>',
]
# trunk: all segments collide (bark + climbable)
for i, (p0, p1, r) in enumerate(trunk_caps):
    lines.append(
        f'    <geom name="tree_0_trunk_{i}" type="capsule" '
        f'fromto="{f6(p0, p1)}" size="{r:.3f}" rgba="{BARK}" '
        f'contype="1" conaffinity="31"/>'
    )
# branches: visual-only for now (climbing comes Phase 5)
for i, (p0, p1, r) in enumerate(branches):
    lines.append(
        f'    <geom name="tree_0_branch_{i}" type="capsule" '
        f'fromto="{f6(p0, p1)}" size="{r:.3f}" rgba="{BARK}" '
        f'contype="0" conaffinity="0"/>'
    )
# foliage: visual ellipsoids, no collision
for i, (c, sz) in enumerate(foliage):
    lines.append(
        f'    <geom name="tree_0_foliage_{i}" type="ellipsoid" '
        f'pos="{f3(c)}" size="{sz[0]:.3f} {sz[1]:.3f} {sz[2]:.3f}" '
        f'rgba="{LEAVES}" contype="0" conaffinity="0"/>'
    )
lines.extend(['  </worldbody>', '</mujocoinclude>', ''])
GROVE.write_text("\n".join(lines))

print(f"Wrote {GROVE}")
print(f"  variety={args.variety} size={size:.2f} → height={height:.2f}m, trunk_r={base_r:.2f}m")
print(f"  branches={n_branches}  leaves={leaves:.2f}  detachment={detach:.2f}")
print(f"  position=({bx:.2f}, {by:.2f}, {bz:.2f})  seed={args.seed}")
